export const SUPPORTED_LOCALES_METADATA: LocaleMetadata[] = Object.values(ALL_LOCALES_METADATA);

export function getLocaleMetadata(locale: AppLocale): LocaleMetadata {
  return ALL_LOCALES_METADATA[locale] || ALL_LOCALES_METADATA.en;
}

export function isRTLLocale(locale: AppLocale): boolean {
  return ALL_LOCALES_METADATA[locale]?.direction === "rtl";
}

export function getEighthScheduleLocales(): LocaleMetadata[] {
  return SUPPORTED_LOCALES_METADATA.filter((m) => m.schedule === "eighth_schedule");
}

export function getRegionalLocales(): LocaleMetadata[] {
  return SUPPORTED_LOCALES_METADATA.filter((m) => m.schedule === "regional");
}

export function getLanguageCoverageSummary() {
  const total = SUPPORTED_LOCALES_METADATA.length;
  const eighthSchedule = getEighthScheduleLocales().length;
  const regional = getRegionalLocales().length;
  const sumCoverage = SUPPORTED_LOCALES_METADATA.reduce((acc, l) => acc + l.coveragePercent, 0);
  const averageCoverage = Math.round(sumCoverage / total);

  return {
    total,
    eighthSchedule,
    regional,
    averageCoverage,
  };
}
