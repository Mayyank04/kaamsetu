export function getLanguageCapability(code: string): LanguageCapability | undefined {
  return ALL_TRANSLATION_CAPABILITIES[code as AppLocale];
}

export function isLanguageSupported(code: string): boolean {
  return Boolean(ALL_TRANSLATION_CAPABILITIES[code as AppLocale]);
}

export function isPairSupported(
  source: string,
  target: string,
  provider?: TranslationProviderType
): boolean {
  if (source === target) return true;
  const srcCap = getLanguageCapability(source);
  const tgtCap = getLanguageCapability(target);
  if (!srcCap || !tgtCap) return false;
  if (!srcCap.sourceSupported || !tgtCap.targetSupported) return false;

  if (provider) {
    return (
      srcCap.supportedProviders.includes(provider) &&
      tgtCap.supportedProviders.includes(provider)
    );
  }

  // Check if there is at least one common provider
  return srcCap.supportedProviders.some((p) => tgtCap.supportedProviders.includes(p));
}

export function getSupportedSourceLanguages(): LanguageCapability[] {
  return Object.values(ALL_TRANSLATION_CAPABILITIES).filter((cap) => cap.sourceSupported);
}

export function getSupportedTargetLanguages(source?: string): LanguageCapability[] {
  return Object.values(ALL_TRANSLATION_CAPABILITIES).filter((cap) => {
    if (!cap.targetSupported) return false;
    if (source && source === cap.code) return false;
    return true;
  });
}
